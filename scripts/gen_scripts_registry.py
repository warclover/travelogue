#!/usr/bin/env python3
"""Generate scripts/README.md and docs/archive/ARCHIVE-CANDIDATES.md (M-C3).

Scans top-level ``scripts/*.py`` for references in CI workflows and docs.
"""

from __future__ import annotations

import argparse
import re
from collections import defaultdict
from dataclasses import dataclass
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPTS_DIR = ROOT / "scripts"
WORKFLOWS_DIR = ROOT / ".github" / "workflows"
DOCS_DIR = ROOT / "docs"
README_PATH = SCRIPTS_DIR / "README.md"
CANDIDATES_PATH = DOCS_DIR / "archive" / "ARCHIVE-CANDIDATES.md"

SCRIPT_REF = re.compile(r"scripts/([A-Za-z0-9_./-]+\.py)")
PHASE_PREFIX = re.compile(r"^phase(\d+)[_.]")


@dataclass(frozen=True)
class ScriptEntry:
    name: str
    path: Path
    ci_refs: tuple[str, ...]
    doc_refs: tuple[str, ...]
    script_refs: tuple[str, ...]

    @property
    def status(self) -> str:
        if self.ci_refs:
            return "CI"
        if self.doc_refs:
            return "docs"
        if self.script_refs:
            return "active"
        if self.name.startswith("_"):
            return "internal"
        if PHASE_PREFIX.match(self.name):
            return "archivable-candidate"
        return "active"


def _rel(path: Path) -> str:
    return path.relative_to(ROOT).as_posix()


def _scan_workflows() -> dict[str, list[str]]:
    refs: dict[str, list[str]] = defaultdict(list)
    if not WORKFLOWS_DIR.is_dir():
        return refs
    for wf in sorted(WORKFLOWS_DIR.glob("*.yml")):
        text = wf.read_text(encoding="utf-8")
        for match in SCRIPT_REF.finditer(text):
            refs[Path(match.group(1)).name].append(_rel(wf))
    return refs


def _scan_docs() -> dict[str, list[str]]:
    refs: dict[str, list[str]] = defaultdict(list)
    for doc in sorted(DOCS_DIR.rglob("*.md")):
        if doc == CANDIDATES_PATH:
            continue
        text = doc.read_text(encoding="utf-8", errors="replace")
        for match in SCRIPT_REF.finditer(text):
            refs[Path(match.group(1)).name].append(_rel(doc))
    return refs


def _scan_scripts() -> dict[str, list[str]]:
    refs: dict[str, list[str]] = defaultdict(list)
    for script in sorted(SCRIPTS_DIR.glob("*.py")):
        text = script.read_text(encoding="utf-8", errors="replace")
        for match in SCRIPT_REF.finditer(text):
            refs[Path(match.group(1)).name].append(_rel(script))
    for script in sorted((SCRIPTS_DIR / "archive").rglob("*.py")):
        text = script.read_text(encoding="utf-8", errors="replace")
        for match in SCRIPT_REF.finditer(text):
            refs[Path(match.group(1)).name].append(_rel(script))
    return refs


def _collect_scripts() -> list[ScriptEntry]:
    entries: list[ScriptEntry] = []
    ci_map = _scan_workflows()
    doc_map = _scan_docs()
    script_map = _scan_scripts()
    for path in sorted(SCRIPTS_DIR.glob("*.py")):
        if path.name == "gen_scripts_registry.py":
            continue
        name = path.name
        entries.append(
            ScriptEntry(
                name=name,
                path=path,
                ci_refs=tuple(sorted(set(ci_map.get(name, [])))),
                doc_refs=tuple(sorted(set(doc_map.get(name, [])))),
                script_refs=tuple(sorted(set(script_map.get(name, [])))),
            )
        )
    return entries


def _format_refs(refs: tuple[str, ...], *, limit: int = 3) -> str:
    if not refs:
        return "—"
    shown = list(refs[:limit])
    if len(refs) > limit:
        shown.append(f"+{len(refs) - limit} more")
    return ", ".join(f"`{r}`" for r in shown)


def _render_readme(entries: list[ScriptEntry]) -> str:
    today = date.today().isoformat()
    counts: dict[str, int] = defaultdict(int)
    for entry in entries:
        counts[entry.status] += 1

    lines = [
        "# Scripts Registry",
        "",
        "> Auto-generated by `scripts/gen_scripts_registry.py` · M-C3 · "
        f"last refresh **{today}**",
        "",
        "Regenerate:",
        "",
        "```bash",
        "python scripts/gen_scripts_registry.py",
        "```",
        "",
        "## Summary",
        "",
        "| Status | Count | Meaning |",
        "|--------|------:|---------|",
        f"| CI | {counts['CI']} | Referenced in `.github/workflows` |",
        f"| docs | {counts['docs']} | Referenced in `docs/` only |",
        f"| active | {counts['active']} | No CI/docs scan hit; keep unless archived |",
        f"| internal | {counts['internal']} | Leading `_` helper / one-off audit |",
        f"| archivable-candidate | {counts['archivable-candidate']} | "
        "`phaseN_*` with zero CI/docs refs · see archive list |",
        "",
        "## Registry",
        "",
        "| Script | Status | CI | Docs | Scripts |",
        "|--------|--------|----|------|---------|",
    ]
    for entry in entries:
        lines.append(
            f"| `{entry.name}` | {entry.status} | "
            f"{_format_refs(entry.ci_refs)} | {_format_refs(entry.doc_refs)} | "
            f"{_format_refs(entry.script_refs)} |"
        )
    lines.extend(
        [
            "",
            "## Archive policy (PRD §6.3)",
            "",
            "Move to `scripts/archive/phase{N}/` only when **all** hold:",
            "",
            "1. Phase acceptance signed off for ≥ one release cycle",
            "2. Zero references in CI workflows and active docs",
            "3. Listed in [docs/archive/ARCHIVE-CANDIDATES.md](../docs/archive/ARCHIVE-CANDIDATES.md) "
            "and confirmed by maintainer",
            "",
        ]
    )
    return "\n".join(lines)


def _render_candidates(entries: list[ScriptEntry]) -> str:
    today = date.today().isoformat()
    candidates = [e for e in entries if e.status == "archivable-candidate"]
    archived = sorted((SCRIPTS_DIR / "archive").rglob("*.py"))
    by_phase: dict[str, list[str]] = defaultdict(list)
    for entry in candidates:
        match = PHASE_PREFIX.match(entry.name)
        phase = match.group(1) if match else "misc"
        by_phase[phase].append(entry.name)

    lines = [
        "# Script archive candidates (M-C3)",
        "",
        f"> Generated **{today}** · **Do not `git mv` without maintainer confirmation.**",
        "",
        "Criteria: `phaseN_*` script · zero hits in `.github/workflows` and `docs/` scans.",
        "",
        f"**Total candidates:** {len(candidates)}",
        "",
    ]
    if not candidates:
        lines.append("_No candidates at this refresh._")
        return "\n".join(lines) + "\n"

    for phase in sorted(by_phase, key=lambda p: int(p) if p.isdigit() else 999):
        lines.append(f"## Phase {phase} ({len(by_phase[phase])})")
        lines.append("")
        for name in sorted(by_phase[phase]):
            lines.append(f"- [ ] `scripts/{name}`")
        lines.append("")

    lines.extend(
        [
            "## Next step",
            "",
            "After confirmation, move batches to `scripts/archive/phase{N}/` and re-run:",
            "",
            "```bash",
            "python scripts/gen_scripts_registry.py",
            "pytest --fast -q",
            "```",
            "",
        ]
    )
    if archived:
        lines.append(f"## Archived ({len(archived)})")
        lines.append("")
        for path in archived:
            lines.append(f"- [x] `{_rel(path)}`")
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit 1 if README or candidates file would change.",
    )
    args = parser.parse_args(argv)

    entries = _collect_scripts()
    readme = _render_readme(entries)
    candidates = _render_candidates(entries)

    if args.check:
        stale = []
        if README_PATH.read_text(encoding="utf-8") != readme:
            stale.append(_rel(README_PATH))
        if CANDIDATES_PATH.read_text(encoding="utf-8") != candidates:
            stale.append(_rel(CANDIDATES_PATH))
        if stale:
            print("Registry stale:", ", ".join(stale))
            print("Run: python scripts/gen_scripts_registry.py")
            return 1
        print("Registry up to date.")
        return 0

    README_PATH.write_text(readme, encoding="utf-8", newline="\n")
    CANDIDATES_PATH.parent.mkdir(parents=True, exist_ok=True)
    CANDIDATES_PATH.write_text(candidates, encoding="utf-8", newline="\n")
    (SCRIPTS_DIR / "archive").mkdir(parents=True, exist_ok=True)
    archive_readme = SCRIPTS_DIR / "archive" / "README.md"
    if not archive_readme.exists():
        archive_readme.write_text(
            "# scripts/archive\n\n"
            "Retired phase one-off scripts (`phaseN_*`) moved per M-C3 policy.\n"
            "See [docs/archive/ARCHIVE-CANDIDATES.md](../../docs/archive/ARCHIVE-CANDIDATES.md).\n",
            encoding="utf-8",
            newline="\n",
        )
    print(f"Wrote {_rel(README_PATH)} ({len(entries)} scripts)")
    print(f"Wrote {_rel(CANDIDATES_PATH)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
