"""Phase 7 pipeline performance checker (AC-P7-01/02/03/05/10/12 proxy).

Usage:
  python scripts/phase7_pipeline_perf.py
  python scripts/phase7_pipeline_perf.py --write
  python scripts/phase7_pipeline_perf.py --write --studio-e2e-ms 230000 --studio-e2e-p95-ms 310000
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
RECORD_PATH = ROOT / "docs" / "acceptance-records" / "phase7-perf-eval.json"
PHASE6_RECORD_PATH = ROOT / "docs" / "acceptance-records" / "phase6-quality-eval.json"


def _now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat()


def _load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def _save_json(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def _git_commit() -> str | None:
    try:
        out = subprocess.check_output(
            ["git", "rev-parse", "HEAD"],
            cwd=ROOT,
            stderr=subprocess.DEVNULL,
            text=True,
        )
        sha = out.strip()
        return sha or None
    except Exception:
        return None


def _pct_drop(base: float | None, cur: float | None) -> float | None:
    if base is None or cur is None or base == 0:
        return None
    return (base - cur) / base * 100.0


def _ensure_record(path: Path) -> dict[str, Any]:
    if path.is_file():
        return _load_json(path)
    return {
        "schemaVersion": "1",
        "benchmarkId": "benchmark-p7-v0.1",
        "commit": "",
        "deviceTier": "S2",
        "deviceNote": "",
        "configSnapshot": "docs/config-phase7.example.yaml",
        "baseline": {"phase": "P6"},
        "candidate": {"phase": "P7"},
        "qualityGuard": {},
        "nr_p7": {},
        "ac_p7": {},
        "notes": "generated by phase7_pipeline_perf.py",
    }


def _set_if_not_none(target: dict[str, Any], key: str, value: float | str | None) -> None:
    if value is not None:
        target[key] = value


def _set_baseline_from_phase6(record: dict[str, Any], phase6: dict[str, Any]) -> None:
    base = record.setdefault("baseline", {})
    kpi = phase6.get("kpiPhase6") or {}
    _set_if_not_none(base, "pipeline_time_1k_sec", kpi.get("pipelineTime1kSec"))
    _set_if_not_none(base, "peak_memory_1k_mb", kpi.get("peakMemory1kMb"))
    bench = phase6.get("benchmark") or {}
    _set_if_not_none(record, "commit", bench.get("commit"))


def _set_candidate_proxy_from_phase6(record: dict[str, Any]) -> dict[str, Any]:
    sys.path.insert(0, str(ROOT))
    from scripts.phase6_benchmark_run import eval_pipeline_perf

    stats = eval_pipeline_perf()
    cand = record.setdefault("candidate", {})
    _set_if_not_none(cand, "pipeline_time_1k_sec", stats.get("pipelineTime1kSecP6"))
    _set_if_not_none(cand, "peak_memory_1k_mb", stats.get("peakMemory1kMbP6"))
    return stats


def _bool_or_none(value: bool | None) -> bool | None:
    if value is None:
        return None
    return bool(value)


def _compute_ac(record: dict[str, Any]) -> dict[str, Any]:
    base = record.get("baseline") or {}
    cand = record.get("candidate") or {}
    ac = record.setdefault("ac_p7", {})

    # AC-P7-01
    d_e2e = _pct_drop(base.get("studio_e2e_250_ms"), cand.get("studio_e2e_250_ms"))
    d_e2e_p95 = _pct_drop(base.get("studio_e2e_250_p95_ms"), cand.get("studio_e2e_250_p95_ms"))
    p50 = cand.get("studio_e2e_250_ms")
    p95 = cand.get("studio_e2e_250_p95_ms")
    ratio_ok = None if (p50 in (None, 0) or p95 is None) else (float(p95) <= float(p50) * 1.6)
    ac01 = None
    if d_e2e is not None and d_e2e_p95 is not None and ratio_ok is not None:
        ac01 = d_e2e >= 30.0 and d_e2e_p95 >= 25.0 and ratio_ok
    ac["AC-P7-01"] = _bool_or_none(ac01)

    # AC-P7-02
    d_ingest = _pct_drop(base.get("ingest_time_250_ms"), cand.get("ingest_time_250_ms"))
    d_clip = _pct_drop(base.get("clip_embed_time_250_ms"), cand.get("clip_embed_time_250_ms"))
    d_clip_p95 = _pct_drop(base.get("clip_embed_time_250_p95_ms"), cand.get("clip_embed_time_250_p95_ms"))
    cp50 = cand.get("clip_embed_time_250_ms")
    cp95 = cand.get("clip_embed_time_250_p95_ms")
    clip_ratio_ok = None if (cp50 in (None, 0) or cp95 is None) else (float(cp95) <= float(cp50) * 1.8)
    ac02 = None
    if d_ingest is not None and d_clip is not None and d_clip_p95 is not None and clip_ratio_ok is not None:
        ac02 = d_ingest >= 25.0 and d_clip >= 40.0 and d_clip_p95 >= 30.0 and clip_ratio_ok
    ac["AC-P7-02"] = _bool_or_none(ac02)

    # AC-P7-03
    inc_fields = [
        cand.get("clip_embed_time_incr_append_10pct_ms"),
        cand.get("clip_embed_time_incr_delete_10pct_ms"),
        cand.get("clip_embed_time_incr_replace_10pct_ms"),
    ]
    base_clip = base.get("clip_embed_time_250_ms")
    drops: list[float] = []
    if base_clip not in (None, 0):
        for field in inc_fields:
            val = _pct_drop(base_clip, field)
            if val is not None:
                drops.append(val)
        if not drops:
            val = _pct_drop(base_clip, cand.get("clip_embed_time_incr_10pct_ms"))
            if val is not None:
                drops.append(val)
    ac03 = None if not drops else all(d >= 60.0 for d in drops)
    ac["AC-P7-03"] = _bool_or_none(ac03)

    # AC-P7-05
    t_base = base.get("pipeline_time_1k_sec")
    t_cur = cand.get("pipeline_time_1k_sec")
    m_base = base.get("peak_memory_1k_mb")
    m_cur = cand.get("peak_memory_1k_mb")
    ac05 = None
    if t_base is not None and t_cur is not None and m_base is not None and m_cur is not None:
        ac05 = float(t_cur) <= float(t_base) * 1.05 and float(m_cur) < float(m_base) * 1.10
    ac["AC-P7-05"] = _bool_or_none(ac05)

    # AC-P7-10 (auto batch)
    auto_batch_win = cand.get("auto_batch_win_rate")
    ac10 = None if auto_batch_win is None else float(auto_batch_win) >= 0.95
    ac["AC-P7-10"] = _bool_or_none(ac10)

    # AC-P7-11 (cache rebuild + NR) is finalized by equivalence script.
    cache_rebuild = cand.get("cache_rebuild_success_rate")
    nr_passed = (record.get("nr_p7") or {}).get("passed")
    ac11 = None
    if cache_rebuild is not None and nr_passed is not None:
        ac11 = float(cache_rebuild) >= 1.0 and bool(nr_passed)
    ac["AC-P7-11"] = _bool_or_none(ac11)

    # AC-P7-12 (recovery after fault injection)
    rollback_recovery = cand.get("rollback_recovery_success")
    ac12 = None if rollback_recovery is None else float(rollback_recovery) >= 1.0
    ac["AC-P7-12"] = _bool_or_none(ac12)

    return {
        "dropStudioPct": d_e2e,
        "dropStudioP95Pct": d_e2e_p95,
        "dropIngestPct": d_ingest,
        "dropClipPct": d_clip,
        "dropClipP95Pct": d_clip_p95,
        "dropClipIncrPctList": drops,
        "autoBatchWinRate": auto_batch_win,
        "cacheRebuildSuccessRate": cache_rebuild,
        "rollbackRecoverySuccess": rollback_recovery,
        "ac_p7": ac,
    }


def _missing_for_perf_gate(record: dict[str, Any]) -> list[str]:
    base = record.get("baseline") or {}
    cand = record.get("candidate") or {}
    needed = {
        "baseline.studio_e2e_250_ms": base.get("studio_e2e_250_ms"),
        "baseline.studio_e2e_250_p95_ms": base.get("studio_e2e_250_p95_ms"),
        "baseline.ingest_time_250_ms": base.get("ingest_time_250_ms"),
        "baseline.clip_embed_time_250_ms": base.get("clip_embed_time_250_ms"),
        "baseline.clip_embed_time_250_p95_ms": base.get("clip_embed_time_250_p95_ms"),
        "candidate.studio_e2e_250_ms": cand.get("studio_e2e_250_ms"),
        "candidate.studio_e2e_250_p95_ms": cand.get("studio_e2e_250_p95_ms"),
        "candidate.ingest_time_250_ms": cand.get("ingest_time_250_ms"),
        "candidate.clip_embed_time_250_ms": cand.get("clip_embed_time_250_ms"),
        "candidate.clip_embed_time_250_p95_ms": cand.get("clip_embed_time_250_p95_ms"),
        "candidate.auto_batch_win_rate": cand.get("auto_batch_win_rate"),
        "candidate.rollback_recovery_success": cand.get("rollback_recovery_success"),
    }
    return [k for k, v in needed.items() if v is None]


def main() -> int:
    parser = argparse.ArgumentParser(description="Phase 7 performance checker and recorder")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--record", type=Path, default=RECORD_PATH)
    parser.add_argument("--phase6-record", type=Path, default=PHASE6_RECORD_PATH)
    parser.add_argument("--strict", action="store_true", help="fail when required perf fields are missing")
    parser.add_argument("--fill-baseline-from-phase6", action="store_true", default=True)
    parser.add_argument("--skip-proxy", action="store_true", help="skip Phase 6 proxy eval for 1k metrics")
    parser.add_argument("--device-tier", default=None)
    parser.add_argument("--device-note", default=None)
    parser.add_argument("--benchmark-id", default=None)
    parser.add_argument("--config-snapshot", default=None)
    parser.add_argument("--studio-e2e-ms", type=float, default=None)
    parser.add_argument("--studio-e2e-p95-ms", type=float, default=None)
    parser.add_argument("--ingest-ms", type=float, default=None)
    parser.add_argument("--clip-ms", type=float, default=None)
    parser.add_argument("--clip-p95-ms", type=float, default=None)
    parser.add_argument("--clip-incr-ms", type=float, default=None)
    parser.add_argument("--clip-incr-append-ms", type=float, default=None)
    parser.add_argument("--clip-incr-delete-ms", type=float, default=None)
    parser.add_argument("--clip-incr-replace-ms", type=float, default=None)
    parser.add_argument("--curate-beam-ms", type=float, default=None)
    parser.add_argument("--auto-batch-win-rate", type=float, default=None)
    parser.add_argument("--cache-rebuild-success-rate", type=float, default=None)
    parser.add_argument("--rollback-recovery-success", type=float, default=None)
    args = parser.parse_args()

    record = _ensure_record(args.record.resolve())
    if args.fill_baseline_from_phase6 and args.phase6_record.is_file():
        phase6 = _load_json(args.phase6_record)
        _set_baseline_from_phase6(record, phase6)

    if not args.skip_proxy:
        proxy_stats = _set_candidate_proxy_from_phase6(record)
    else:
        proxy_stats = {"skipped": True}

    # Top-level metadata
    _set_if_not_none(record, "commit", _git_commit())
    _set_if_not_none(record, "deviceTier", args.device_tier)
    _set_if_not_none(record, "deviceNote", args.device_note)
    _set_if_not_none(record, "benchmarkId", args.benchmark_id)
    _set_if_not_none(record, "configSnapshot", args.config_snapshot)

    base = record.setdefault("baseline", {})
    cand = record.setdefault("candidate", {})
    base["recordedAt"] = base.get("recordedAt") or _now()
    cand["recordedAt"] = _now()

    # Manual candidate inputs
    _set_if_not_none(cand, "studio_e2e_250_ms", args.studio_e2e_ms)
    _set_if_not_none(cand, "studio_e2e_250_p95_ms", args.studio_e2e_p95_ms)
    _set_if_not_none(cand, "ingest_time_250_ms", args.ingest_ms)
    _set_if_not_none(cand, "clip_embed_time_250_ms", args.clip_ms)
    _set_if_not_none(cand, "clip_embed_time_250_p95_ms", args.clip_p95_ms)
    _set_if_not_none(cand, "clip_embed_time_incr_10pct_ms", args.clip_incr_ms)
    _set_if_not_none(cand, "clip_embed_time_incr_append_10pct_ms", args.clip_incr_append_ms)
    _set_if_not_none(cand, "clip_embed_time_incr_delete_10pct_ms", args.clip_incr_delete_ms)
    _set_if_not_none(cand, "clip_embed_time_incr_replace_10pct_ms", args.clip_incr_replace_ms)
    _set_if_not_none(cand, "curate_beam_time_250_ms", args.curate_beam_ms)
    _set_if_not_none(cand, "auto_batch_win_rate", args.auto_batch_win_rate)
    _set_if_not_none(cand, "cache_rebuild_success_rate", args.cache_rebuild_success_rate)
    _set_if_not_none(cand, "rollback_recovery_success", args.rollback_recovery_success)

    summary = _compute_ac(record)
    summary["missing"] = _missing_for_perf_gate(record)
    summary["proxy"] = proxy_stats
    summary["record"] = str(args.record.resolve())
    print(json.dumps(summary, indent=2, ensure_ascii=False))

    if args.write:
        _save_json(args.record.resolve(), record)
        print(json.dumps({"written": str(args.record.resolve())}, indent=2, ensure_ascii=False))

    if args.strict and summary["missing"]:
        return 2

    failed = [
        key
        for key in ("AC-P7-01", "AC-P7-02", "AC-P7-03", "AC-P7-05", "AC-P7-10", "AC-P7-12")
        if (record.get("ac_p7") or {}).get(key) is False
    ]
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())

