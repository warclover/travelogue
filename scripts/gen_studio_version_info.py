#!/usr/bin/env python3
"""Generate PyInstaller Windows version resource from packaging/VERSION (D-INS-10).

Maps marketing version ``0.2.0-beta.N`` → FileVersion ``0.2.0.N``.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGING = ROOT / "packaging"
OUT = PACKAGING / "file_version_info.txt"


def parse_marketing_version(raw: str) -> tuple[str, tuple[int, int, int, int]]:
    ver = raw.strip().splitlines()[0].strip()
    if not ver:
        raise SystemExit("packaging/VERSION is empty")
    m = re.fullmatch(
        r"(\d+)\.(\d+)\.(\d+)(?:-beta\.(\d+))?(?:[-+][0-9A-Za-z.-]+)?",
        ver,
    )
    if not m:
        raise SystemExit(f"unsupported VERSION format: {ver!r} (want 0.2.0-beta.N)")
    major, minor, patch = int(m.group(1)), int(m.group(2)), int(m.group(3))
    build = int(m.group(4) or 0)
    return ver, (major, minor, patch, build)


def render_version_info(marketing: str, filevers: tuple[int, int, int, int]) -> str:
    a, b, c, d = filevers
    file_ver = f"{a}.{b}.{c}.{d}"
    # Escape for Python string literals inside the version file.
    prod = marketing.replace("\\", "\\\\").replace("'", "\\'")
    return f"""# UTF-8
#
# Auto-generated by scripts/gen_studio_version_info.py — do not edit by hand.
# Source: packaging/VERSION → {marketing} → FileVersion {file_ver}
#
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({a}, {b}, {c}, {d}),
    prodvers=({a}, {b}, {c}, {d}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          '040904B0',
          [
            StringStruct('CompanyName', 'Travelogue'),
            StringStruct('FileDescription', 'Travelogue Studio'),
            StringStruct('FileVersion', '{file_ver}'),
            StringStruct('InternalName', 'TravelogueStudio'),
            StringStruct('LegalCopyright', 'Copyright (c) Travelogue contributors'),
            StringStruct('OriginalFilename', 'TravelogueStudio.exe'),
            StringStruct('ProductName', 'Travelogue Studio'),
            StringStruct('ProductVersion', '{prod}'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--version-file",
        type=Path,
        default=PACKAGING / "VERSION",
        help="marketing version source",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=OUT,
        help="PyInstaller version resource path",
    )
    args = parser.parse_args(argv)
    marketing, filevers = parse_marketing_version(
        args.version_file.read_text(encoding="utf-8")
    )
    text = render_version_info(marketing, filevers)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8")
    print(f"OK: {args.out} ← {marketing} → FileVersion {'.'.join(map(str, filevers))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
